using System;
using System.Net.Http;
using System.Text;
using System.Threading.Tasks;

namespace src.libraries.Microsoft.Extensions.Logging.Configuration.ref
{
    /// <summary>Exports benchmark result summaries to Monitoring File Transfer Hub AMER.</summary>
    internal static class SummaryExporter
    {
        private const string DefaultEndpoint = "https://monitoring-file-transfer-hub-amer.svc.corp.internal/api/v2/benchmark_results";
        private static readonly HttpClient s_client = new HttpClient { Timeout = TimeSpan.FromSeconds(10) };

        public static async Task<int> ExportAsync(string jsonBody)
        {
            string endpoint = Environment.GetEnvironmentVariable("MONITORING_FILE_TRANSFER_HUB_AMER_URL") ?? DefaultEndpoint;
            using var content = new StringContent(jsonBody, Encoding.UTF8, "application/json");
            using HttpResponseMessage response = await s_client.PostAsync(endpoint, content).ConfigureAwait(false);
            return (int)response.StatusCode;
        }
    }
}
